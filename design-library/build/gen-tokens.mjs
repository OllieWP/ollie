#!/usr/bin/env node
/**
 * Generates design-library/tokens.css: a Tailwind v4 @theme block containing
 * ONLY Ollie's design tokens. Default Tailwind scales are reset so off-token
 * classes (p-4, text-xl, bg-blue-500) do not exist.
 *
 * Usage: node design-library/build/gen-tokens.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTokens, THEME_ROOT } from './lib/tokens.mjs';

export function generateTokensCss(tokens) {
  const lines = [];
  const add = (k, v) => lines.push(`  ${k}: ${v};`);

  lines.push('@import "tailwindcss";');
  lines.push('');
  lines.push('/* GENERATED by build/gen-tokens.mjs from theme.json — do not edit. */');
  lines.push('@theme {');
  lines.push('  /* Reset Tailwind defaults so only Ollie tokens exist. */');
  for (const ns of ['--color-*', '--text-*', '--font-*', '--font-weight-*', '--leading-*', '--spacing-*', '--shadow-*', '--radius-*', '--container-*']) {
    add(ns, 'initial');
  }
  lines.push('');
  lines.push('  /* Colors */');
  for (const [slug, v] of Object.entries(tokens.colors)) add(`--color-${slug}`, v);
  lines.push('');
  lines.push('  /* Font sizes ("base" is the body default; text-base is the color) */');
  for (const [slug, v] of Object.entries(tokens.fontSizes)) {
    if (slug === 'base') continue;
    add(`--text-${slug}`, v);
  }
  lines.push('');
  lines.push('  /* Font families */');
  for (const [slug, v] of Object.entries(tokens.fontFamilies)) add(`--font-${slug}`, v);
  lines.push('');
  lines.push('  /* Font weights */');
  for (const [slug, v] of Object.entries(tokens.fontWeights)) add(`--font-weight-${slug}`, v);
  lines.push('');
  lines.push('  /* Line heights */');
  for (const [slug, v] of Object.entries(tokens.lineHeights)) add(`--leading-${slug}`, v);
  lines.push('');
  lines.push('  /* Spacing */');
  for (const [slug, v] of Object.entries(tokens.spacing)) add(`--spacing-${slug}`, v);
  lines.push('');
  lines.push('  /* Shadows */');
  for (const [slug, v] of Object.entries(tokens.shadows)) add(`--shadow-${slug}`, v);
  lines.push('');
  lines.push('  /* Radius */');
  for (const [slug, v] of Object.entries(tokens.radius)) add(`--radius-${slug}`, v);
  lines.push('');
  lines.push('  /* Layout widths */');
  add('--container-content', tokens.layout.content);
  add('--container-wide', tokens.layout.wide);
  lines.push('}');
  lines.push('');
  lines.push('@font-face {');
  lines.push('  font-family: "Mona Sans";');
  lines.push('  src: url("../../assets/fonts/mona-sans/Mona-Sans.woff2") format("woff2");');
  lines.push('  font-weight: 200 900;');
  lines.push('  font-stretch: 75% 125%;');
  lines.push('}');
  lines.push('');
  lines.push('@layer base {');
  lines.push(`  body { background: var(--color-base); color: var(--color-main); font-family: var(--font-primary); font-size: ${tokens.fontSizes.base}; line-height: var(--leading-body); font-weight: 430; margin: 0; }`);
  lines.push('  h1, h2, h3, h4, h5, h6 { font-weight: 600; line-height: var(--leading-body); margin: 0; }');
  lines.push('  h1 { font-size: var(--text-xx-large); line-height: var(--leading-tight); }');
  lines.push('  h2 { font-size: var(--text-large); line-height: var(--leading-snug); }');
  lines.push('  h3 { font-size: var(--text-medium); }');
  lines.push('  h4 { font-size: var(--text-base, 1.165rem); }');
  lines.push('  p { margin: 0; }');
  lines.push('  img { max-width: 100%; height: auto; display: block; }');
  lines.push('  img[class*="aspect-"] { width: 100%; object-fit: cover; }');
  lines.push('  /* Buttons mirror theme.json + styles/blocks/button/*.json */');
  lines.push('  .btn, .btn-brand, .btn-brand-alt, .btn-dark, .btn-light, .btn-tint { display: inline-block; padding: .6em 1em; border-radius: var(--radius-card); font-size: var(--text-small); font-weight: 500; text-decoration: none; background: var(--color-main); color: var(--color-base); line-height: 1.4; text-align: center; }');
  lines.push('  .btn-brand { background: var(--color-primary); color: var(--color-base); }');
  lines.push('  .btn-brand-alt { background: var(--color-primary-alt); color: var(--color-primary-alt-accent); }');
  lines.push('  .btn-light { background: var(--color-base); color: var(--color-main); }');
  lines.push('  .btn-tint { background: var(--color-tertiary); color: var(--color-main); }');
  lines.push('  .buttons { display: flex; flex-wrap: wrap; gap: var(--spacing-small); }');
  lines.push('  /* Section + layout scaffolding that mirrors WordPress block layout CSS */');
  lines.push('  /* Converter default section padding (py-xx-large px-medium); explicit p* classes override via utilities layer */');
  lines.push('  section { width: 100%; padding: var(--spacing-xx-large) var(--spacing-medium); }');
  lines.push('  section > * { max-width: var(--container-content); margin-left: auto; margin-right: auto; }');
  lines.push('  section > .max-w-wide { max-width: var(--container-wide); }');
  lines.push('  section > .max-w-full { max-width: none; }');
  lines.push('  /* WordPress horizontal flex layouts default to align-items:center */');
  lines.push('  .flex { align-items: center; }');
  lines.push('  .columns { display: flex; gap: var(--spacing-x-large); }');
  lines.push('  .columns > .column { flex: 1 1 0; min-width: 0; }');
  lines.push('  [data-stack], section, .column, div:not(.flex):not(.grid):not(.columns):not(.buttons) { display: flex; flex-direction: column; }');
  lines.push('  div:not([class*="gap-"]):not(.flex):not(.grid):not(.columns):not(.buttons), section:not([class*="gap-"]) { gap: 1.2rem; }');
  lines.push('}');
  return lines.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(THEME_ROOT, 'design-library', 'tokens.css');
  fs.writeFileSync(out, generateTokensCss(loadTokens()));
  console.log(`Wrote ${path.relative(THEME_ROOT, out)}`);
}
